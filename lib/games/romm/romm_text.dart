/// Stable IDs live in en.i18n.json and the translation provenance catalog.
/// The English map also supports older generated Slang catalogs during a
/// source-only handoff; normal Slang generation makes translated keys available.
String rommText(BuildContext context, String key) {
  final id = key.startsWith('romm.') ? key.substring(5) : key;
  final translated = context.t['romm.$id'];
  return translated is String ? translated : rommEnglish[id] ?? rommEnglish['connectionFailed']!;
}

