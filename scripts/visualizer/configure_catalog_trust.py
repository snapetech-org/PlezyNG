#!/usr/bin/env python3
"""Pin a reviewed public MilkRust catalog root in every Flutter platform build.

No network, key generation, secret input, signing or builds. Fetch the public
root from the reviewed immutable MilkRust revision before invoking this tool.
The resulting Dart source is committed and reviewed with the app release.
"""
from __future__ import annotations

import argparse
import base64
import binascii
import hashlib
import json
import os
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "lib/services/visualization/visualizer_release_trust.dart"


def require(condition, reason):
    if not condition:
        raise ValueError(reason)


def configuration(raw, revision, digest):
    require(re.fullmatch(r"[a-f0-9]{40}", revision), "expected immutable MilkRust revision")
    require(re.fullmatch(r"[a-f0-9]{64}", digest), "expected reviewed root SHA-256")
    require(hashlib.sha256(raw).hexdigest() == digest, "root digest does not match review")
    require(0 < len(raw) <= 16384, "public root exceeds limit")

    def unique(pairs):
        values = {}
        for key, value in pairs:
            require(key not in values, "duplicate root field")
            values[key] = value
        return values

    data = json.loads(raw, object_pairs_hook=unique)
    require(isinstance(data, dict) and data.get("schemaVersion") == 1,
            "unsupported root schema")
    require(data.get("status") == "active", "production root has not been activated")
    keys = data.get("keys")
    require(isinstance(keys, dict) and 1 <= len(keys) <= 16, "public keys are not provisioned")
    seen = set()
    for key_id, encoded in keys.items():
        require(re.fullmatch(r"[a-z0-9_-]{1,64}", key_id) and isinstance(encoded, str), "invalid key")
        public = base64.b64decode(encoded, validate=True)
        require(len(public) == 32 and base64.b64encode(public).decode() == encoded,
                "expected canonical base64 Ed25519 public key")
        require(public not in seen, "aliases cannot count as independent signing keys")
        seen.add(public)
    threshold, floor = data.get("threshold"), data.get("minimumSequence")
    require(type(threshold) is int and 1 <= threshold <= len(keys), "invalid quorum")
    require(type(floor) is int and 1 <= floor <= 9007199254740991, "invalid release sequence floor")
    pinned = json.dumps({"keys": keys, "threshold": threshold, "minimumSequence": floor},
                        sort_keys=True, separators=(",", ":"))
    # Validation limits every emitted character to Dart-safe JSON literals.
    return ("// Generated by scripts/visualizer/configure_catalog_trust.py.\n"
            "// Public trust material; changes require release review.\n"
            f"const visualizerReleaseTrustJson = '{pinned}';\n"
            f"const visualizerReleaseTrustRevision = '{revision}';\n"
            f"const visualizerReleaseTrustSha256 = '{digest}';\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--source-revision", required=True)
    parser.add_argument("--sha256", required=True)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    args = parser.parse_args()
    with args.input.open("rb") as source:
        raw = source.read(16385)
    output = configuration(raw, args.source_revision, args.sha256)
    if args.check:
        require(OUTPUT.read_text() == output, "app pin differs from reviewed public root")
    else:
        temporary = OUTPUT.with_suffix(".dart.partial")
        with temporary.open("x", encoding="utf-8", newline="\n") as target:
            target.write(output)
            target.flush()
            os.fsync(target.fileno())
        os.replace(temporary, OUTPUT)
    print("Catalog public root matches the app source pin." if args.check else
          "Catalog public root pinned; review and commit the generated Dart source.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, TypeError, OSError, binascii.Error):
        raise SystemExit("Catalog trust configuration rejected; check public root, revision, digest and quorum.") from None
