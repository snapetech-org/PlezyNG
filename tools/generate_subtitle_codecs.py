"""Generate portable, strict legacy subtitle decoding tables from CPython codecs.

This is data generation, not runtime charset guessing. No network or third-party
packages are used. Keep this script with the generated Dart tables so the codec
mapping revision can be reproduced. Undefined byte sequences remain errors.
"""
import base64
import pathlib
import struct
import sys
import zlib

SINGLE = [*(f"cp{n}" for n in range(1250, 1259)), "latin_1", "iso8859_2",
          "iso8859_5", "iso8859_6", "iso8859_7", "iso8859_8", "iso8859_9",
          "iso8859_15", "koi8_r", "koi8_u", "cp437", "cp850", "cp866"]
DOUBLE = ["cp932", "gbk", "gb18030", "big5", "cp949"]

def codepoint(data, codec):
    try:
        value = data.decode(codec, errors="strict")
        return ord(value) if len(value) == 1 else 0xffffffff
    except UnicodeDecodeError:
        return 0xffffffff

def table(codec):
    values = [codepoint(bytes([b]), codec) for b in range(256)]
    if codec in DOUBLE:
        values.extend(codepoint(bytes([a, b]), codec) for a in range(256) for b in range(256))
    raw = b"".join(struct.pack("<I", value) for value in values)
    return base64.b64encode(zlib.compress(raw, 9)).decode("ascii")

def ranges():
    output = []
    previous = None
    for pointer in range(126 * 10 * 126 * 10):
        n = pointer
        d, n = n % 10 + 0x30, n // 10
        c, n = n % 126 + 0x81, n // 126
        b, a = n % 10 + 0x30, n // 10 + 0x81
        value = codepoint(bytes([a, b, c, d]), "gb18030")
        if value == 0xffffffff:
            previous = None
            continue
        if previous is not None and value == previous + 1:
            output[-1][1] = pointer
        else:
            output.append([pointer, pointer, value])
        previous = value
    return output

def main():
    destination = pathlib.Path(__file__).resolve().parents[1] / "lib/services/subtitle_codec_tables.dart"
    with destination.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by tools/generate_subtitle_codecs.py; do not edit by hand.\n")
        stream.write(f"// Mapping source: CPython {sys.version.split()[0]} standard-library codecs.\n")
        stream.write("// Each zlib table is 256 single-byte entries, then optional 65536 pairs;\n// uint32 little-endian Unicode scalar values, 0xffffffff means undefined.\n")
        stream.write("const subtitleCodecTables = <String, String>{\n")
        for codec in SINGLE + DOUBLE:
            encoded = table(codec)
            stream.write(f"  '{codec}':\n")
            for offset in range(0, len(encoded), 120):
                stream.write(f"      '{encoded[offset:offset + 120]}'\n")
            stream.write("  ,\n")
        stream.write("};\n\nconst subtitleGb18030Ranges = <List<int>>[\n")
        for first, last, scalar in ranges():
            stream.write(f"  [{first}, {last}, {scalar}],\n")
        stream.write("];\n")

if __name__ == "__main__":
    main()
