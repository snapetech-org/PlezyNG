import hashlib
import subprocess
import tempfile
import unittest
from pathlib import Path

from tools.webos.verify_sdk_checkout import CheckoutError, _verify_patch


class VerifySdkCheckoutTests(unittest.TestCase):
    def _git(self, repo: Path, *args: str) -> bytes:
        result = subprocess.run(
            ["git", "-C", str(repo), *args],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        return result.stdout

    def _repository(self, root: Path) -> Path:
        repo = root / "sdk"
        repo.mkdir()
        self._git(repo, "init", "--quiet")
        self._git(repo, "config", "user.name", "SDK test")
        self._git(repo, "config", "user.email", "sdk-test@example.invalid")
        (repo / "patched.txt").write_text("base\n", encoding="utf-8")
        (repo / "generated.lock").write_text("base lock\n", encoding="utf-8")
        self._git(repo, "add", "patched.txt", "generated.lock")
        self._git(repo, "commit", "--quiet", "-m", "base")
        return repo

    def test_ignores_generated_changes_outside_reviewed_patch_paths(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            repo = self._repository(root)
            (repo / "patched.txt").write_text("reviewed change\n", encoding="utf-8")
            patch = self._git(repo, "-c", "core.abbrev=8", "diff", "HEAD", "--binary", "--", "patched.txt")
            patch_path = root / "reviewed.patch"
            patch_path.write_bytes(patch)
            expected_hash = hashlib.sha256(patch).hexdigest()

            # gclient sync may regenerate tracked lockfiles outside the patch.
            (repo / "generated.lock").write_text("generated by gclient\n", encoding="utf-8")
            self._git(repo, "config", "core.abbrev", "10")

            _verify_patch(repo, patch_path, expected_hash, [])

    def test_patch_accepts_different_git_abbreviation_settings(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            repo = self._repository(root)
            self._git(repo, "config", "core.abbrev", "7")
            (repo / "patched.txt").write_text("reviewed change\n", encoding="utf-8")
            patch = self._git(repo, "diff", "HEAD", "--binary", "--", "patched.txt")
            patch_path = root / "reviewed.patch"
            patch_path.write_bytes(patch)
            expected_hash = hashlib.sha256(patch).hexdigest()
            self._git(repo, "config", "core.abbrev", "10")

            _verify_patch(repo, patch_path, expected_hash, [])

    def test_added_patch_file_is_verified_with_stable_abbreviation(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            repo = self._repository(root)
            self._git(repo, "config", "core.abbrev", "7")
            (repo / "patched.txt").write_text("reviewed change\n", encoding="utf-8")
            added_path = repo / "z-added.txt"
            added_path.write_text("new reviewed file\n", encoding="utf-8")
            tracked_diff = self._git(repo, "diff", "HEAD", "--binary", "--", "patched.txt")
            added = subprocess.run(
                [
                    "git",
                    "-C",
                    str(repo),
                    "diff",
                    "--no-index",
                    "--binary",
                    "--",
                    "/dev/null",
                    "z-added.txt",
                ],
                check=False,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            self.assertEqual(added.returncode, 1, added.stderr.decode("utf-8", errors="replace"))
            patch = tracked_diff + added.stdout
            patch_path = root / "reviewed.patch"
            patch_path.write_bytes(patch)
            expected_hash = hashlib.sha256(patch).hexdigest()
            self._git(repo, "config", "core.abbrev", "10")

            _verify_patch(repo, patch_path, expected_hash, ["z-added.txt"])
            added_path.write_text("unreviewed drift\n", encoding="utf-8")
            with self.assertRaisesRegex(CheckoutError, "SDK source differs from reviewed patch"):
                _verify_patch(repo, patch_path, expected_hash, ["z-added.txt"])

    def test_rejects_drift_in_a_reviewed_patch_path(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            repo = self._repository(root)
            (repo / "patched.txt").write_text("reviewed change\n", encoding="utf-8")
            patch = self._git(repo, "diff", "HEAD", "--binary", "--", "patched.txt")
            patch_path = root / "reviewed.patch"
            patch_path.write_bytes(patch)
            expected_hash = hashlib.sha256(patch).hexdigest()
            (repo / "patched.txt").write_text("unreviewed drift\n", encoding="utf-8")

            with self.assertRaisesRegex(CheckoutError, "SDK source differs from reviewed patch"):
                _verify_patch(repo, patch_path, expected_hash, [])


if __name__ == "__main__":
    unittest.main()
